export const proposalLabel = (copy: PromptEditCopy, status: PromptVersionResponse["status"]): string =>
  status === "PENDING" ? copy.PROPOSAL_PENDING : status === "REJECTED" ? copy.PROPOSAL_REJECTED : copy.PROPOSAL_DRAFT;

export const fill = (template: string, values: Record<string, string | number>): string =>
  Object.entries(values).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), template);
